export type Language = "en" | "nl";
export const languageOf = (value: unknown): Language => (String(value ?? "").toLowerCase().startsWith("nl") ? "nl" : "en");
export const textsFor = (language: Language): Texts => (language === "nl" ? nl : en);
/** A time in seconds as text, with a decimal comma in Dutch. */
export const localTime = (text: string, language: Language) => (language === "nl" ? text.replace(".", ",") : text);
